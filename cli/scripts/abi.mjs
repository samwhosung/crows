// Copies ABIs from the Foundry build and deployment addresses into the CLI. Run after `forge build` or a deploy.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../contracts/out");
const pick = (file, name) => JSON.parse(readFileSync(join(out, file, `${name}.json`), "utf8")).abi;
const abis = {
  crowsAbi: pick("Crows.sol", "Crows"),
  resolverAbi: pick("IDuelResolver.sol", "IDuelResolver"),
  feedAbi: pick("PriceAt.sol", "IAggregatorV3"),
  mockFeedAbi: pick("MockFeed.sol", "MockFeed"),
  lobbyAbi: pick("Lobby.sol", "Lobby"),
};
let ts = "// Generated by scripts/abi.mjs from contracts/out. Do not edit.\n";
for (const [k, v] of Object.entries(abis)) ts += `export const ${k} = ${JSON.stringify(v, null, 2)} as const;\n\n`;
writeFileSync(join(here, "../src/abi.generated.ts"), ts);

const dep = join(here, "../../contracts/deployments");
const dst = join(here, "../deployments");
mkdirSync(dst, { recursive: true });
for (const f of readdirSync(dep).filter((f) => f.endsWith(".json"))) copyFileSync(join(dep, f), join(dst, f));
console.log("wrote src/abi.generated.ts and deployments/");
